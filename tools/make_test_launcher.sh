#!/bin/sh
#
# Generate /sdcard/test/ on an M68 SD card, which overrides the stock launcher.
#
# /etc/init.d/S50ui checks for /sdcard/test at boot and, if it exists, runs
# /sdcard/test/test.sh instead of /usr/bin/game. Nothing in the read-only
# rootfs is touched, so deleting the directory restores stock behaviour.
#
# Usage:
#   make_test_launcher.sh [-t TARGET] [-m WxH] [-n] DEST
#
#   DEST     mounted data partition of the card (e.g. /Volumes/SDCARD),
#            or any staging directory to copy over later
#   -t       lvui | game | retroarch | shell   (default: lvui)
#   -m       HDMI output mode, e.g. 1920x1080 (default: leave the stock
#            choice, which is 1280x720). The UI keeps drawing at 1280x720
#            and is scaled up; RetroArch renders at the output size.
#   -n       no watchdog: do not fall back to the stock launcher
#
# Targets:
#   lvui       /usr/bin/lvui, the unused LVGL launcher. See the warning below.
#   game       the stock MiniGUI launcher. Use this first to prove the hook
#              works before trying anything that might not come up.
#   retroarch  boot straight into one ROM, no menu.
#   shell      bring up no UI at all; start adbd and idle. Recovery target —
#              reach the box over the serial console or adb.
#
set -eu

TARGET=lvui
WATCHDOG=1
MODE=

usage() { sed -n '2,/^set -eu/p' "$0" | sed 's/^# \{0,1\}//;$d'; exit "${1:-0}"; }

while getopts "t:m:nh" opt; do
    case "$opt" in
        t) TARGET=$OPTARG ;;
        m) MODE=$OPTARG ;;
        n) WATCHDOG=0 ;;
        h) usage 0 ;;
        *) usage 2 ;;
    esac
done
shift $((OPTIND - 1))

[ $# -eq 1 ] || usage 2
DEST=$1

case "$TARGET" in
    lvui|game|retroarch|shell) ;;
    *) echo "unknown target: $TARGET" >&2; exit 2 ;;
esac

case "$MODE" in
    ''|[0-9]*x[0-9]*) ;;
    *) echo "bad mode '$MODE', want WxH like 1920x1080" >&2; exit 2 ;;
esac

[ -d "$DEST" ] || { echo "no such directory: $DEST" >&2; exit 1; }

TESTDIR=$DEST/test
mkdir -p "$TESTDIR/lib"

# ---------------------------------------------------------------- test.sh ---
# Written to the card. Everything below runs on the device, under busybox ash.
#
# Two things S50ui gets wrong that we have to undo:
#   LD_LIBRARY_PATH=LD_LIBRARY_PATH:/sdcard/test/lib   <- missing the '$'
#   MG_CFG_PATH=/sdcard/test                           <- no MiniGUI.cfg there
#
cat > "$TESTDIR/test.sh" <<'DEVICE_SCRIPT'
#!/bin/sh
#
# Generated by tools/make_test_launcher.sh. Edit TARGET below to switch.
# Delete /sdcard/test (or `touch /sdcard/test/DISABLE`) to get the stock UI back.
#
TARGET=@TARGET@
WATCHDOG=@WATCHDOG@
MODE=@MODE@

TESTDIR=/sdcard/test
LOG=$TESTDIR/test.log
STOCK=/usr/bin/game
STOCK_CFG=/usr/local/share/minigui/hdmicfg

# RetroArch target: which core and ROM. game_type numbers are in NOTES.md.
RA_CORE=/usr/local/share/minigui/retro_lib/fbalpha2012_libretro.so
RA_CFG=/usr/local/share/minigui/gbx66.cfg
RA_ROM=/sdcard/game/cps/kof97.zip

# The log is the only way to see what happened without a serial cable, so it
# goes on the card where it survives a reboot and can be read on a PC. Keep one
# previous boot and cap growth -- this is a flash card.
if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 262144 ]; then
    mv -f "$LOG" "$LOG.1"
fi
exec >>"$LOG" 2>&1
echo "=============== $(date) boot, target=$TARGET ==============="
set -x

# Panic switch: lets you recover by creating one file rather than deleting a
# directory, which matters if the card is awkward to get at.
if [ -e "$TESTDIR/DISABLE" ]; then
    set +x
    echo "DISABLE present, handing back to the stock launcher"
    export MG_CFG_PATH=$STOCK_CFG
    exec "$STOCK"
fi

# S50ui has already: enabled HDMI, run drm-hotplug.sh, mounted userdata on
# /data, and set XDG_CONFIG_HOME=/sdcard/. It has also set the two variables
# below to values we do not want.
export LD_LIBRARY_PATH="/sdcard/test/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
unset MG_CFG_PATH

# HDMI mode. drm-hotplug.sh (run by S50ui) wrote the first match from
#   PREFERED_MODES="1280x720 1024x 1280x1024 800x600 1920x1080 [0-9]"
# to /tmp/drm_mode.cfg. MiniGUI's drmcon and the vendor RetroArch both read
# that file, as WxH only, and take the FIRST connector mode of that size --
# so the refresh rate is whatever the TV's EDID lists first (720p50 and
# 720p60 have the same pixel clock, so the kernel sort does not split them).
# Log what the TV offers, in order, so the refresh rate can be explained.
HDMI=/sys/class/drm/card0-HDMI-A-1
cat "$HDMI/modes"
modetest -M rockchip -c | sed -n '/HDMI/,/props:/p'
cat /tmp/drm_mode.cfg
if [ -n "$MODE" ]; then
    if grep -q "^$MODE" "$HDMI/modes"; then
        echo "$MODE" > /tmp/drm_mode.cfg
        # Keep the UI's framebuffer at the size MiniGUI.cfg draws at; the VOP
        # scales it to the output mode.
        export MINIGUI_DRM_FB_MODE=1280x720
        export MINIGUI_DRM_DEBUG=1
    else
        echo "TV does not offer $MODE, keeping $(cat /tmp/drm_mode.cfg)"
    fi
fi
# Record the mode actually set (with refresh) once the launcher is up.
( sleep 8; modetest -M rockchip -p | sed -n '/^CRTCs:/,/^Planes:/p' ) &

# Input routing. start_game.sh uses 4 while RetroArch has the pad and 1 when a
# UI does; 6 is PPSSPP. The node is absent on some units, hence the guard.
set_key_mode() {
    [ -w /sys/devices/platform/key_mode.0/key_mode ] || return 0
    echo "$1" > /sys/devices/platform/key_mode.0/key_mode
}

start_lvui() {
    # WARNING: lvui reads its images from /usr/local/share/lvgl/{picture,game,
    # music,video} and only picture/nosdbg.png is present in this firmware. It
    # also wants resources under /sdcard/minigui/res. It is a leftover from a
    # sibling handheld model and will probably come up blank or not at all.
    # Stage what we can and let it try.
    if [ ! -d /sdcard/minigui/res ] && [ -d /usr/local/share/minigui/res ]; then
        mkdir -p /sdcard/minigui
        cp -a /usr/local/share/minigui/res /sdcard/minigui/res
    fi
    set_key_mode 1
    /usr/bin/lvui &
    echo $! > /tmp/launcher.pid
}

start_game() {
    export MG_CFG_PATH=$STOCK_CFG
    "$STOCK" &
    echo $! > /tmp/launcher.pid
}

start_retroarch() {
    set_key_mode 4
    /usr/bin/retroarch -c "$RA_CFG" -L "$RA_CORE" "$RA_ROM" &
    echo $! > /tmp/launcher.pid
}

start_shell() {
    # No UI. adbd plus an idle loop, so init does not respawn anything over us
    # and the serial getty stays usable.
    set_key_mode 1
    /usr/bin/adbd &
    echo $! > /tmp/launcher.pid
}

case "$TARGET" in
    lvui)      start_lvui ;;
    game)      start_game ;;
    retroarch) start_retroarch ;;
    shell)     start_shell ;;
    *)         echo "unknown target '$TARGET'"; start_game ;;
esac

PID=$(cat /tmp/launcher.pid)

if [ "$WATCHDOG" = 1 ] && [ "$TARGET" != game ] && [ "$TARGET" != shell ]; then
    # Give it 15s to stay alive. A launcher that dies leaves a black screen and
    # no way in without pulling the card, so fall back rather than hang.
    i=0
    while [ $i -lt 15 ]; do
        kill -0 "$PID" 2>/dev/null || break
        i=$((i + 1))
        sleep 1
    done
    if ! kill -0 "$PID" 2>/dev/null; then
        set +x
        echo "$TARGET exited within ${i}s -- falling back to $STOCK"
        echo "see $LOG"
        set -x
        start_game
        PID=$(cat /tmp/launcher.pid)
    fi
fi

wait "$PID"
echo "launcher pid $PID exited with $?"
DEVICE_SCRIPT

# Substitute the build-time choices into the device script.
sed -i.bak \
    -e "s|^TARGET=@TARGET@|TARGET=$TARGET|" \
    -e "s|^WATCHDOG=@WATCHDOG@|WATCHDOG=$WATCHDOG|" \
    -e "s|^MODE=@MODE@|MODE=$MODE|" \
    "$TESTDIR/test.sh"
rm -f "$TESTDIR/test.sh.bak"
chmod 755 "$TESTDIR/test.sh"

cat > "$TESTDIR/README.txt" <<EOF
M68 launcher override — generated $(date -u '+%Y-%m-%d %H:%M UTC')

target: $TARGET
watchdog: $WATCHDOG
mode: ${MODE:-stock}

/etc/init.d/S50ui runs test.sh instead of /usr/bin/game because this directory
exists. Output lands in test.log on this card; read it there after a boot.

To get the stock launcher back, either:
  - delete this whole 'test' directory, or
  - create an empty file called DISABLE next to this README.

The 'lib' directory is prepended to LD_LIBRARY_PATH; drop .so files in it to
override a rootfs library without touching the read-only rootfs.
EOF

echo "wrote $TESTDIR/"
ls -l "$TESTDIR"
echo
echo "target: $TARGET, watchdog: $WATCHDOG, mode: ${MODE:-stock}"
case "$TARGET" in
lvui)
cat <<'EOF'

Note on the lvui target: that binary's resources are not in this firmware.
It expects /usr/local/share/lvgl/{picture,game,music,video}/ and only
picture/nosdbg.png exists. Expect a blank screen; the watchdog will hand
back to the stock launcher if it exits. Read test.log afterwards.
EOF
;;
esac
cat <<'EOF'

If the card is FAT, check the exec bit survived the copy — S50ui invokes
/sdcard/test/test.sh directly and a non-executable file silently does nothing.
EOF
